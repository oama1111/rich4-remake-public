export const helpScreen: UiScreen = {
  id: 'help',

  /**
   * ★ **浮窗**（原版从不擦屏，靠存底/还原）：
   *
   * @source 回调 `_rich4_ui_help_callback` 的 `WM_CREATE`（`loc_0044e488`）里
   *   `call fcn_00451e7e`（**存底**，VA 0x00451e7e）、`WM_RBUTTONUP`（`loc_0044e546`）
   *   里 `call fcn_00451edb`（**还原** + `Post`，VA 0x00451edb）—— 原版**一条
   *   全屏清色都没有**，面板四周一直是原来的棋盘。少了这个 `windowed`，
   *   `main.ts` 不会先把棋盘画一遍，四周就是纯黑。
   *（`big-map-screen.ts:222` 是同一个用法。）
   *
   * ⚠️ **已知限制**：`main.ts` 只在 `screen === 'game'` 时预画棋盘
   *   （`main.ts` 的 `if (overlay.windowed === true && screen === 'game')`），
   *   所以从**設定屏**里点「遊戲說明」推开的这一屏四周仍是黑的。
   *   那要动 `main.ts`（本卡不许），登记在 `docs/deviations/T-045.md` D-045-5。
   */
  windowed: true,

  active: () => helpState.open,

  draw(env) {
    drawHelpScreen(env.stage, (i) => env.sprite('help.mkf', HELP_RESOURCE, i, false), {
      chapter: helpState.chapter,
      scroll: helpState.scroll,
      origin: { x: helpState.panelX, y: helpState.panelY },
    });
  },

  down(x, y, env) {
    // 舞台坐标 → 面板局部（原版比的就是局部坐标）
    const hit = hitHelp(x - helpState.panelX, y - helpState.panelY);
    if (hit === null) return;
    applyHelpHit(hit, env);
  },

  hotkey(fn, env) {
    // 熱鍵 H（`HOTKEY.help` = 24）开关本屏
    if (fn === HOTKEY.help) {
      if (helpState.open) closeHelp(env);
      else openHelp(env);
      return true;
    }
    // ★ `Escape` = 关掉**最上面那一扇窗**（原版是全局鍵盤处理把顶层窗口收掉）。
    //   本屏是登记的整屏，main.ts 那条通用的 ESC 只认它自己的 `Screen`，
    //   认不到这一层 —— 设定屏里按「遊戲說明」推开本屏之后，ESC 就没人接。
    if (fn === HOTKEY.cancel) {
      if (!helpState.open) return false;
      closeHelp(env);
      return true;
    }
    return false;
  },

  /**
   * 右键 = 关掉本屏。@source `_rich4_ui_help_callback` 的 0x205 → `loc_0044e546`：
   * `play_sound_effect(0, 0x482332)`（音效 4）+ 放掉那几张图 + `Post_0402_Message(0)`。
   *
   * ★ 与上面那条 `Escape` 是**同一个行为**：原版钩子把取消键补成 `WM_RBUTTONUP`
   *   （@source VA 0x004011c3），主窗口过程只交给 `windowCallbacks` 栈顶。
   *   少了它，「從工具列開的遊戲百科」就只有 ESC 一条出口（需求方第 3 条）。
   */
  contextmenu(_x, _y, env) {
    if (!helpState.open) return;
    // 取消音 —— 与 `panel-cancel.ts` 的 `CANCEL_SOUND` 同一个号（`[0x482332] = 4`）
    env.playEffect(CANCEL_SOUND);
    closeHelp(env);
  },

  toolbar(index, env) {
    // 「遊戲百科」= 工具列下标 0 @source 跳表 0x417d39 第 0 项
    if (index !== HELP_TOOLBAR_INDEX) return false;
    openHelpAt(env, HELP_PANEL.x, HELP_PANEL.y);
    return true;
  },
};
