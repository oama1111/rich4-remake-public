/** 一个命中矩形（**面板局部**坐标，左闭右闭）*/
export interface HelpBox {
  readonly x0: number;
  readonly y0: number;
  readonly x1: number;
  readonly y1: number;
}

/** 命中项的序号（0..5，**不能**当成「第几颗钮」）*/
export type HelpHit = 0 | 1 | 2 | 3 | 4 | 5;

/**
 * 六条矩形 @source `0x476254` 起 24 个 dword，逐条 dump：
 * `22,38,91,104 | 77,38,104,78 | 170,43,192,58 | 170,59,192,74 | 322,48,345,80 | 343,48,366,80`
 */
export const HELP_HIT_BOXES: readonly HelpBox[] = [
  { x0: 22, y0: 38, x1: 91, y1: 104 },
  { x0: 77, y0: 38, x1: 104, y1: 78 },
  { x0: 170, y0: 43, x1: 192, y1: 58 },
  { x0: 170, y0: 59, x1: 192, y1: 74 },
  { x0: 322, y0: 48, x1: 345, y1: 80 },
  { x0: 343, y0: 48, x1: 366, y1: 80 },
];

/** 六条矩形 → 三组：0 = 左列八格、1 = 上一章/下一章、2 = 上滚/下滚 */
export const HELP_HIT_LABEL: readonly number[] = [0, 0, 1, 1, 2, 2];
/** 同一组里的第几个格子（0 = 第一个、1 = 第二个）*/
export const HELP_HIT_CELL: readonly number[] = [0, 1, 0, 1, 0, 1];

function inBox(x: number, y: number, b: HelpBox): boolean {
  return x >= b.x0 && x <= b.x1 && y >= b.y0 && y <= b.y1;
}

/**
 * 点在左列第几格上；没点中返回 null。
 *
 * ★ 这 8 格不是命中表里的条目：原版左列在**图上**就画好了，命中按
 *   「左上 (22, 38)、每格高 18、间隙 3」那套图几何判（见 `chipY`）。
 *   上下两端各留 0 像素 —— 第 8 格的下沿是 38 + 8×21 − 3 = 203。
 */
export function hitHelpChip(x: number, y: number): number | null {
  if (x < HELP_HIT_BOXES[0]!.x0 || x > HELP_HIT_BOXES[0]!.x1) return null;
  const rel = y - HELP_CHIP_DY;
  if (rel < 0) return null;
  const step = HELP_CHIP_H + HELP_CHIP_GAP;
  const i = Math.floor(rel / step);
  if (i < 0 || i >= HELP_CHAPTER_COUNT) return null;
  // 只认格内那 18 像素，间隙不算
  return rel - i * step < HELP_CHIP_H ? i : null;
}

/**
 * 点在六条矩形里的哪一条上；没点中返回 null。
 *
 * @param x,y **面板局部**坐标（0..399）—— 原版的矩形就是拿局部坐标比的
 *   （`esi = 鼠标 x − [0x48c5e4]`，@0x44e592）。调用方按 `HELP_PANEL` 减一下。
 */
export function hitHelpBox(x: number, y: number): HelpHit | null {
  for (let i = 0; i < HELP_HIT_BOXES.length; i++) {
    if (inBox(x, y, HELP_HIT_BOXES[i]!)) return i as HelpHit;
  }
  return null;
}

/**
 * 完整命中：先认左列八格（`{ label: 0, cell: 格号 }`），再认六条矩形。
 * 没点中返回 null —— 原版这时 `xor eax, eax` 直接返回，什么都不做。
 */
export function hitHelp(x: number, y: number): { label: number; cell: number } | null {
  const chip = hitHelpChip(x, y);
  if (chip !== null) return { label: 0, cell: chip };
  const box = hitHelpBox(x, y);
  if (box === null) return null;
  return { label: HELP_HIT_LABEL[box]!, cell: HELP_HIT_CELL[box]! };
}

