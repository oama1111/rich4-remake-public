/** 降序比较器，与 `0x42bed0` / `0x42d0ef` 同形：a > b ⇒ −1，a < b ⇒ +1 */
const desc = (a: { k: number }, b: { k: number }): number => (a.k > b.k ? -1 : a.k < b.k ? 1 : 0);

describe('watcomQsort —— 原版 VA 0x00457e6c', () => {
  it('小段（n < 16）第一趟 gap = 3 只排 0,3,6… 那一条链 ⇒ 同键会被越过（不稳定）', () => {
    // 手算：gap 3：cmp(A1, D2) > 0 ⇒ 换 → [D, B, C, A]；gap 1：再无交换 ⇒ D 排在 B 前面
    const r = watcomQsort(
      [
        { id: 'A', k: 1 },
        { id: 'B', k: 2 },
        { id: 'C', k: 1 },
        { id: 'D', k: 2 },
      ],
      desc,
      false,
    );
    expect(r.map((x) => x.id).join('')).toBe('DBCA');
  });

  it('小段：无交叉时就是稳定的插入排序', () => {
    const r = watcomQsort(
      ['A1', 'B1', 'C2', 'D1', 'E2'].map((s) => ({ id: s[0]!, k: Number(s[1]) })),
      desc,
      false,
    );
    expect(r.map((x) => x.id).join('')).toBe('CEABD');
  });

  it('大段（三路划分）结果按比较器有序，且不改入参', () => {
    for (const pivotInPlace of [false, true]) {
      for (const n of [16, 17, 29, 30, 42, 43, 64, 120]) {
        const input = Array.from({ length: n }, (_, i) => ({ id: i, k: (i * 7919) % 11 }));
        const copy = input.map((x) => ({ ...x }));
        const r = watcomQsort(input, desc, pivotInPlace);
        expect(input).toEqual(copy);
        expect(r.length).toBe(n);
        for (let i = 1; i < n; i++) expect(r[i - 1]!.k).toBeGreaterThanOrEqual(r[i]!.k);
        expect(new Set(r.map((x) => x.id)).size).toBe(n);
      }
    }
  });

  it('大段：枢轴换到段首（1 字节元素）与拷贝枢轴（4 字节元素）的同键次序可以不同', () => {
    const input = Array.from({ length: 40 }, (_, i) => ({ id: i, k: [5, 3, 5, 1][i % 4]! }));
    const a = watcomQsort(input, desc, true).map((x) => x.id);
    const b = watcomQsort(input, desc, false).map((x) => x.id);
    expect(a).not.toEqual(b);
  });
});

