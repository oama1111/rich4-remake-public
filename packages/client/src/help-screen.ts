/** 每按一次上/下滚走的行数 = 一屏 8 行 @source 0x44e6eb / 0x44e944 的 `8` */
export const HELP_SCROLL_STEP = HELP_TEXT.rows;

/** 夹取章号到 `[0, 章数−1]` */
export function clampChapter(i: number): number {
  if (!Number.isFinite(i)) return 0;
  return Math.min(HELP_CHAPTER_COUNT - 1, Math.max(0, Math.trunc(i)));
}

/**
 * 夹取章节内行偏移到 `[0, maxScroll]`。
 *
 * @source 0x44e944 的下滚分支：`edx = [entry+0x0C] − 8`（exe 口径 = **资源数 − 8**，
 *   本模块把它换成当章的 `maxScroll = 行数 − 8`，见 `HELP_CHAPTERS` 那段）；
 *   够走一步就走 8，走不过去就**直接落到 maxScroll**（不做取整）。
 * @source 0x44e881 的上滚分支：`maxScroll <= 0` 就什么都不做，否则退 8 或归 0。
 */
export function clampScroll(chapter: number, scroll: number): number {
  const c = HELP_CHAPTERS[clampChapter(chapter)];
  const max = c === undefined ? 0 : Math.max(0, c.maxScroll);
  if (!Number.isFinite(scroll)) return 0;
  return Math.min(max, Math.max(0, Math.trunc(scroll)));
}

/**
 * 该章共几屏（0 基的最后一屏 + 1）。
 *
 * 原版没有这个数 —— 它只在 `[0, maxScroll]` 上按 8 步走。这里按同一套步长
 * 算出来（`floor(maxScroll/8) + 1`），给测试与「頁次」读数用。
 * 八章依次是 **1 / 3 / 1 / 2 / 1 / 1 / 93 / 12**。
 */
export function pageCount(chapter: number): number {
  const c = HELP_CHAPTERS[clampChapter(chapter)];
  const max = c === undefined ? 0 : Math.max(0, c.maxScroll);
  return Math.floor(max / HELP_SCROLL_STEP) + 1;
}

/** 当前行偏移落在第几屏（0 基），与 `pageCount` 同一套步长 */
export function pageOf(chapter: number, scroll: number): number {
  return Math.floor(clampScroll(chapter, scroll) / HELP_SCROLL_STEP);
}

/** 第 `page` 屏的行偏移（夹取到 `[0, maxScroll]`）*/
export function scrollOfPage(chapter: number, page: number): number {
  // ⚠️ 这里夹的是**屏号**（0..pageCount−1），不是章号 —— 别顺手调 clampChapter
  const p = Number.isFinite(page) ? Math.max(0, Math.trunc(page)) : 0;
  return clampScroll(chapter, p * HELP_SCROLL_STEP);
}

/** 该章正文的全部行（含空行与 `@` 分页行）*/
export function chapterLines(chapter: number): readonly string[] {
  return HELP_LINES[clampChapter(chapter)] ?? [];
}

/** 这一屏要画的 8 行（`@` 分页行原样留着，由 `drawHelpScreen` 认它不画）*/
export function visibleLines(
  chapter: number,
  scroll: number,
  rows = HELP_TEXT.rows,
): readonly string[] {
  const at = clampScroll(chapter, scroll);
  return chapterLines(chapter).slice(at, at + rows);
}

/**
 * 这一屏之后还有内容吗 —— 原版那个 `[0x48c5ec]` 标志
 * （`cmp byte [esi + eax], 0x40 / je loc_0044e21e` @0x44e1f2）。
 */
export function hasMoreBelow(
  chapter: number,
  scroll: number,
  rows = HELP_TEXT.rows,
): boolean {
  const lines = chapterLines(chapter);
  const at = clampScroll(chapter, scroll);
  if (at + rows < lines.length) return true;
  // 走到末尾但**当屏**里有分页标记，也算「还能往下」
  return visibleLines(chapter, scroll, rows).includes('@');
}

