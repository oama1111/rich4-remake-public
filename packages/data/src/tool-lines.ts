/**
 * 某个角色用某件道具时说的那句话；越界返回 `null`（道具号只可能 1..13）。
 */
export function toolLine(character: number, toolId: number): ToolLine | null {
  const row = TOOL_LINES[character];
  if (row === undefined) return null;
  return row[toolId - 1] ?? null;
}
